export function buildRoleProfiles(pitchCatalog) {
  const roles = pitchCatalog.Roles.map((role) => {
    const mapped = ROLE_KEY_MAP[role.Id];
    if (!mapped) {
      throw new Error(`Missing role profile mapping for Role.Id="${role.Id}"`);
    }
    const phase = role.Id.startsWith("OP") ? "OOP" : "IP";
    return {
      Id: role.Id,
      Name: role.Name,
      Phase: phase,
      Keys: mapped.keys,
      ...(mapped.aliases ? { Aliases: mapped.aliases } : {}),
    };
  });

  return {
    AllAttributes: ALL_49_ATTRIBUTES,
    Goalkeeping: GK_11_ATTRIBUTES,
    LowerIsBetter: LOWER_IS_BETTER,
    PersonalityKeys: PERSONALITY_KEYS,
    PositionKeys: POSITION_14_KEYS,
    SpecialistRoles: SPECIALIST_ROLES,
    Roles: roles,
  };
}

