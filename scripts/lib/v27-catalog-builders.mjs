function makeStandardThresholds(maxScore) {
  // Calibrated 0.5 to 5.0 star thresholds (step 0.5) matching FM coaching star curve
  const ratios = [0.0, 0.18, 0.30, 0.42, 0.52, 0.62, 0.72, 0.80, 0.88, 0.94];
  return ratios.map((r, i) => ({
    minScore: Math.round(maxScore * r * 10) / 10,
    stars: (i + 1) * 0.5,
  }));
}

